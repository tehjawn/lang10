const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/** Kana rows are [character, romaji]; the romaji doubles as the English answer. */
const kana = (unit: string, rows: [string, string][]): Item[] =>
  rows.map(([ja, romaji]) => ({
    id: `${unit}-${romaji}`,
    unit,
    ja,
    kana: ja,
    romaji,
    en: romaji,
  }));

/** Vocab rows are [written, kana, romaji, english, ...alternates]. */
const vocab = (unit: string, rows: [string, string, string, string, string[]?][]): Item[] =>
  rows.map(([ja, kanaForm, romaji, en, alt]) => ({
    id: `${unit}-${slug(romaji)}`,
    unit,
    ja,
    kana: kanaForm,
    romaji,
    en,
    ...(alt ? { alt } : {}),
  }));

